package com.coungard.univer.service;

import java.util.UUID;

/**
 * Аккаунт пользователя целиком: локальный профиль и логин в Keycloak (issue #133).
 */
public interface AccountService {

  /**
   * Удалить аккаунт пользователя по его собственной просьбе — сразу, без отложенного удаления.
   *
   * <p>Студент: удаляются профиль ({@code Student} и {@code Person}), записи на курсы, отметки посещаемости
   * (преподавателя и собственные) и заявки на добавление вуза. Преподаватель: удаляется профиль, а у пар,
   * лекций и предметов он просто отвязывается — расписание групп остаётся. Отзывы обоих обезличиваются.
   * Журнал аудита не меняется: в нём только UUID, которые после удаления ни на кого не указывают.
   *
   * <p>Сначала данные в БД, последним шагом — пользователь в Keycloak (вместе с его сессиями и
   * refresh-токенами), всё в одной транзакции: если Keycloak недоступен, БД откатывается и удаление можно
   * повторить, «живого» логина без профиля не остаётся. Повторный вызов для уже удалённого аккаунта — не
   * ошибка.
   *
   * @param userId subject JWT = id студента или преподавателя
   * @throws com.coungard.univer.exception.AccountDeletionException не удалось удалить пользователя в Keycloak
   */
  void deleteAccount(UUID userId);
}
