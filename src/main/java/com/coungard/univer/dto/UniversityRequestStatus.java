package com.coungard.univer.dto;

/**
 * Статус заявки студента на добавление университета ({@code UniversityRequest}).
 */
public enum UniversityRequestStatus {

  /** Необработанная — ждёт администратора; студент может её обновить. */
  PENDING,

  /** Выполнена — университет добавлен администратором либо студент сам выбрал университет. */
  COMPLETED,

  /** Отклонена администратором: не университет, дубль, мусор. */
  REJECTED
}
