-- Регистрация студента/преподавателя переходит на сбор даты рождения вместо даты зачисления
-- (студент) и кафедры (преподаватель) — см. issue #79. Дата зачисления и кафедра теперь
-- назначаются позже администратором, а не на регистрации, поэтому оба поля становятся
-- необязательными на уровне схемы; дата рождения хранится в Person, так как используется и
-- студентом, и преподавателем.
ALTER TABLE students ALTER COLUMN enrollment_date DROP NOT NULL;
ALTER TABLE persons ADD COLUMN birthday DATE;
