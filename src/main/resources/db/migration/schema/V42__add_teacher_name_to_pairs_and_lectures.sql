-- Преподаватель пары и занятия текстом (issue #104).
--
-- Студент, заполняющий расписание группы, чаще всего не может сослаться на зарегистрированного
-- преподавателя — большинства реальных преподавателей в системе нет. Необязательное имя текстом
-- рядом с teacher_id: «Иванов И. И.». Если задан teacher_id, имя не хранится — берётся из Teacher.
-- Занятия, сгенерированные из пары, получают имя из неё, как и teacher_id.
ALTER TABLE pairs ADD COLUMN teacher_name VARCHAR(100);

ALTER TABLE lectures ADD COLUMN teacher_name VARCHAR(100);
