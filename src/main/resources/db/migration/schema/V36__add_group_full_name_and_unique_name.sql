-- Создание группы студентом при регистрации (issue #86).
--
-- full_name — необязательная полная расшифровка названия группы («У530» → «Разработка программных и
-- информационных систем»). Само название остаётся свободной строкой и на части не разбирается.
ALTER TABLE student_groups ADD COLUMN full_name VARCHAR(255);

-- Название группы уникально в пределах семестра без учёта регистра и крайних пробелов. Сервис
-- проверяет это сам и отвечает 409; индекс страхует от гонки, когда двое одногруппников создают
-- одну и ту же группу одновременно.
CREATE UNIQUE INDEX uq_student_group_semester_name ON student_groups (semester_id, lower(btrim(name)));
