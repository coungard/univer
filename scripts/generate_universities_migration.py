FIELD_RE = re.compile(r"^-\s*\*\*([^:*]+):\*\*\s*(.*)$")
YEAR_RE = re.compile(r"\b(1[5-9]\d{2}|20[0-2]\d)\b")
DIGITS_RE = re.compile(r"(\d[\d\s ]*\d|\d)")
UNKNOWN_MARK = "требует уточнения"


def sql_str(value):
    if value is None:
        return "NULL"
    escaped = str(value).replace("'", "''")
    return f"'{escaped}'"


def sql_int(value):
    return "NULL" if value is None else str(value)


def parse_file(path: Path):
    text = path.read_text(encoding="utf-8")
    fields = {}
    for line in text.splitlines():
        m = FIELD_RE.match(line.strip())
        if m:
            fields[m.group(1).strip()] = m.group(2).strip()

    full_name = fields.get("Полное название")
    short_name = fields.get("Сокращённое название")
    raw_city = fields.get("Город")
    raw_year = fields.get("Год основания", "")
    raw_rector = fields.get("Ректор", "")
    raw_address = fields.get("Адрес", "")
    raw_site = fields.get("Сайт", "")
    raw_students = fields.get("Число студентов", "")

    if raw_city not in CITY_REGION:
        raise ValueError(f"{path.name}: неизвестный город {raw_city!r}, добавьте его в CITY_REGION")
    city, region = CITY_REGION[raw_city]

    name = short_name or full_name or path.stem
    description = full_name or short_name

    year_match = YEAR_RE.search(raw_year) if UNKNOWN_MARK not in raw_year else None
    founding_year = int(year_match.group(1)) if year_match else None

    rector = None if (not raw_rector or UNKNOWN_MARK in raw_rector) else raw_rector[:255]

    student_count = None
    if raw_students and UNKNOWN_MARK not in raw_students:
        digits_match = DIGITS_RE.search(raw_students)
        if digits_match:
            student_count = int(re.sub(r"[\s ]", "", digits_match.group(1)))

    website = None
    if raw_site and UNKNOWN_MARK not in raw_site:
        website = raw_site.rstrip("/")

    domain = None
    if website:
        domain = re.sub(r"^https?://", "", website)
        domain = domain.split("/")[0]
        domain = re.sub(r"^www\.", "", domain)

    address_text = None
    postal_code = None
    street = None
    if raw_address and UNKNOWN_MARK not in raw_address:
        address_text = raw_address
        # Обычный формат: "[почтовый индекс, ][регион, ]г. Город, Улица, д. N".
        # Ищем "г. Город" где угодно в строке: всё до него (если начинается с
        # 5-6 цифр) -- индекс, всё после него (после запятой) -- улица.
        m = re.search(r"(?:г\.|город)\s*([^,]+)", raw_address)
        if m:
            prefix = raw_address[: m.start()].strip().strip(",").strip()
            suffix = raw_address[m.end():].strip().lstrip(",").strip()
            postal_match = re.match(r"^(\d{5,6})\b", prefix)
            postal_code = postal_match.group(1) if postal_match else None
            street = suffix or f"г. {city}"
        else:
            street = raw_address
    else:
        address_text = f"г. {city}, {region}"
        street = f"г. {city}"

    return {
        "file": path.name,
        "name": name[:255],
        "description": description,
        "country": "Россия",
        "region": region[:100],
        "city": city[:100],
        "address": address_text,
        "postal_code": postal_code,
        "street": street,
        "website": website,
        "email": f"info@{domain}" if domain else None,
        "rector": rector,
        "founding_year": founding_year,
        "student_count": student_count,
    }


